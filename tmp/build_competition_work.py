def shade(cell, fill='F2F2F2'):
    tcPr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement('w:shd')
    shd.set(qn('w:fill'), fill)
    tcPr.append(shd)


def borders(cell):
    tcPr = cell._tc.get_or_add_tcPr()
    el = OxmlElement('w:tcBorders')
    for edge in ('top','left','bottom','right'):
        item = OxmlElement('w:'+edge)
        item.set(qn('w:val'), 'single')
        item.set(qn('w:sz'), '4')
        item.set(qn('w:color'), 'D9D9D9')
        el.append(item)
    tcPr.append(el)


def table(headers, rows, widths=None):
    t = doc.add_table(rows=1, cols=len(headers))
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.autofit = False
    if widths:
        for i, width in enumerate(widths): t.columns[i].width = Cm(width)
    for i, text in enumerate(headers):
        cell = t.rows[0].cells[i]
        if widths: cell.width = Cm(widths[i])
        cell.text = text
        shade(cell, 'E8E8E8')
        borders(cell)
        cell.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER
        for par in cell.paragraphs:
            par.paragraph_format.first_line_indent = Cm(0)
            par.paragraph_format.space_after = Pt(0)
            for run in par.runs: run.bold = True
    for row in rows:
        cells = t.add_row().cells
        for i, text in enumerate(row):
            if widths: cells[i].width = Cm(widths[i])
            cells[i].text = text
            borders(cells[i])
            cells[i].vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER
            for par in cells[i].paragraphs:
                par.paragraph_format.first_line_indent = Cm(0)
                par.paragraph_format.space_after = Pt(0)
                for run in par.runs: run.font.size = Pt(10)
    doc.add_paragraph().paragraph_format.space_after = Pt(0)
    return t


def figure(number, subject, instruction):
    t = doc.add_table(rows=1, cols=1)
    t.autofit = False
    t.rows[0].height = Cm(4.2)
    t.rows[0].height_rule = WD_ROW_HEIGHT_RULE.AT_LEAST
    t.columns[0].width = Cm(14.8)
    cell = t.cell(0,0)
    cell.width = Cm(14.8)
    cell.height = Cm(3.2)
    shade(cell, 'F7F7F7')
    borders(cell)
    cell.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER
    cell.text = f'[МЕСТО ДЛЯ ФОТО / СКРИНШОТА]\n{instruction}'
    for para in cell.paragraphs:
        para.alignment = WD_ALIGN_PARAGRAPH.CENTER
        para.paragraph_format.first_line_indent = Cm(0)
        para.paragraph_format.space_after = Pt(3)
        for run in para.runs: run.font.size = Pt(10); run.font.bold = True
    caption = doc.add_paragraph(style='Figure Caption')
    caption.alignment = WD_ALIGN_PARAGRAPH.CENTER
    caption.add_run(f'Рисунок {number} — {subject}')
    return t


