const counterIconAssets = [
  ['Клюква', 'cranberry.png'],
  ['Огонь', 'fire.png'],
  ['Сердце', 'heart.png'],
];
const counterIconRows = await base64Rows(counterIconAssets);
const counterIconBlock = `// <generated:counter-icons>
// Generated by scripts/embed-assets.mjs from assets/cranberry.png, fire.png, and heart.png.
const COUNTER_ICON_PNG = Object.freeze({
${counterIconRows.join('\n')}
});
const COUNTER_ICON_IMAGE_HASHES = {};
const COUNTER_ICON_ART_SIZE = Object.freeze({ 'Клюква': 40, 'Огонь': 32, 'Сердце': 28 });

function counterIconNode(name) {
  if (!COUNTER_ICON_PNG[name]) throw new Error('Нет изображения счётчика: ' + name);
  if (!COUNTER_ICON_IMAGE_HASHES[name]) {
    COUNTER_ICON_IMAGE_HASHES[name] = figma.createImage(figma.base64Decode(COUNTER_ICON_PNG[name])).hash;
  }
  const frame = figma.createFrame();
  frame.name = name;
  frame.resize(24, 24);
  frame.fills = [];
  frame.clipsContent = true;
  const art = figma.createRectangle();
  art.name = 'Иллюстрация';
  const artSize = COUNTER_ICON_ART_SIZE[name] || 24;
  art.resize(artSize, artSize);
  art.x = (24 - artSize) / 2;
  art.y = (24 - artSize) / 2;
  art.fills = [{ type: 'IMAGE', scaleMode: 'FIT', imageHash: COUNTER_ICON_IMAGE_HASHES[name] }];
  frame.appendChild(art);
  return frame;
}
// </generated:counter-icons>`;

const animationAssets = [1, 2, 3, 4, 5].map((n) => [String(n), `fox-animation-0${n}.png`]);
const animationRows = await base64Rows(animationAssets);
const animationBlock = `// <generated:fox-animation>
// Five 2×2 sprite sheets; frame index 0..19, 240×160 viewport per pose.
const FOX_ANIMATION_PNG = Object.freeze({
${animationRows.join('\n')}
});
const FOX_ANIMATION_HASHES = {};
function foxAnimationFrame(index) {
  const sheetNumber = String(Math.floor(index / 4) + 1);
  if (!FOX_ANIMATION_HASHES[sheetNumber]) {
    FOX_ANIMATION_HASHES[sheetNumber] = figma.createImage(figma.base64Decode(FOX_ANIMATION_PNG[sheetNumber])).hash;
  }
  const frame = figma.createFrame();
  frame.name = 'Лиса · уникальная поза ' + String(index + 1).padStart(2, '0');
  frame.resize(240, 160);
  frame.fills = [];
  frame.clipsContent = true;
  const art = figma.createRectangle();
  art.name = 'Лист ' + sheetNumber + ' · кадр ' + (index % 4 + 1);
  art.resize(480, 320);
  art.fills = [{ type: 'IMAGE', scaleMode: 'FILL', imageHash: FOX_ANIMATION_HASHES[sheetNumber] }];
  frame.appendChild(art);
  art.x = -(index % 2) * 240;
  art.y = -Math.floor(index % 4 / 2) * 160;
  return frame;
}
// </generated:fox-animation>`;


let code = await readFile(codePath, 'utf8');
const mascotPattern = /\/\/ <generated:mascot-images>[\s\S]*?\/\/ <\/generated:mascot-images>/;
const legacyMascotPattern = /const EMOTIONS = \[[\s\S]*?function foxSvg\(emotion\) \{[^\n]*\}/;
const placePattern = /\/\/ <generated:place-images>[\s\S]*?\/\/ <\/generated:place-images>\s*/;
const legacyPlacePattern = /\/\/ Места 120×116[\s\S]*?(?=\/\/ Белые значки шагов пути)/;
const chestPattern = /\/\/ <generated:chest-images>[\s\S]*?\/\/ <\/generated:chest-images>/;
const legacyChestPattern = /const CHEST = \{[\s\S]*?\n\};/;
const counterIconPattern = /\/\/ <generated:(?:counter-icons|cranberry-image)>[\s\S]*?\/\/ <\/generated:(?:counter-icons|cranberry-image)>/;
const spritePattern = /\/\/ <generated:fox-sprite>[\s\S]*?\/\/ <\/generated:fox-sprite>/;
const animationPattern = /\/\/ <generated:fox-animation>[\s\S]*?\/\/ <\/generated:fox-animation>/;
const counterIconAnchor = '// ---------------------------------------------------------------------\n// SVG-ассеты';

const selectedMascotPattern = mascotPattern.test(code) ? mascotPattern : legacyMascotPattern;
const selectedPlacePattern = placePattern.test(code) ? placePattern : legacyPlacePattern;
const selectedChestPattern = chestPattern.test(code) ? chestPattern : legacyChestPattern;
if (!selectedMascotPattern.test(code)) throw new Error('Mascot source block was not found in code.js');
if (!selectedPlacePattern.test(code)) throw new Error('Place source block was not found in code.js');
if (!selectedChestPattern.test(code)) throw new Error('Chest source block was not found in code.js');

code = code.replace(selectedMascotPattern, mascotBlock);
code = code.replace(selectedPlacePattern, placeBlock + '\n\n');
code = code.replace(selectedChestPattern, chestBlock);
if (counterIconPattern.test(code)) code = code.replace(counterIconPattern, counterIconBlock);
else {
  if (!code.includes(counterIconAnchor)) throw new Error('Counter icon insertion anchor was not found in code.js');
  code = code.replace(counterIconAnchor, counterIconBlock + '\n\n' + counterIconAnchor);
}
if (spritePattern.test(code)) code = code.replace(spritePattern, '');
if (animationPattern.test(code)) code = code.replace(animationPattern, animationBlock);
else code = code.replace(counterIconAnchor, animationBlock + '\n\n' + counterIconAnchor);
await writeFile(codePath, code, 'utf8');
console.log(`Embedded mascot, place, chest, counter icon, and 5 animation sheets into ${path.relative(process.cwd(), codePath)}`);
