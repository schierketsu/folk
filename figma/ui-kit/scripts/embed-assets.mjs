import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const scriptsDir = path.dirname(fileURLToPath(import.meta.url));
const pluginDir = path.resolve(scriptsDir, '..');
const codePath = path.join(pluginDir, 'code.js');
const assetsDir = path.join(pluginDir, 'assets');

async function base64Rows(entries) {
  return Promise.all(entries.map(async ([key, file]) => {
    const data = await readFile(path.join(assetsDir, file));
    return `  ${JSON.stringify(key)}: ${JSON.stringify(data.toString('base64'))},`;
  }));
}

const mascotAssets = [
  ['Бежит', 'mascot-running.png'],
  ['Сидит', 'mascot-sitting.png'],
  ['Объясняет', 'mascot-explaining.png'],
];

const mascotRows = await base64Rows(mascotAssets);
const mascotBlock = `// <generated:mascot-images>
// Generated by scripts/embed-assets.mjs from assets/mascot-*.png.
const MASCOT_POSES = ['Бежит', 'Сидит', 'Объясняет'];
const MASCOT_PNG = Object.freeze({
${mascotRows.join('\n')}
});
const MASCOT_IMAGE_HASHES = {};

function mascotNode(pose) {
  const resolvedPose = MASCOT_PNG[pose] ? pose : 'Сидит';
  if (!MASCOT_IMAGE_HASHES[resolvedPose]) {
    MASCOT_IMAGE_HASHES[resolvedPose] = figma.createImage(figma.base64Decode(MASCOT_PNG[resolvedPose])).hash;
  }
  const frame = figma.createFrame();
  frame.name = resolvedPose;
  frame.resize(120, 120);
  frame.fills = [];
  frame.clipsContent = false;
  const art = figma.createRectangle();
  art.name = 'Иллюстрация';
  art.resize(120, 80);
  art.x = 0;
  art.y = 20;
  art.fills = [{ type: 'IMAGE', scaleMode: 'FIT', imageHash: MASCOT_IMAGE_HASHES[resolvedPose] }];
  frame.appendChild(art);
  return frame;
}
// </generated:mascot-images>`;

const placeAssets = [
  ['manpupuner', 'place-manpupuner-map.png', 'place-manpupuner-card.png'],
  ['shanga', 'place-shanga-map.png', 'place-shanga-card.png'],
];
const mapRows = await base64Rows(placeAssets.map(([key, map]) => [key, map]));
const cardRows = await base64Rows(placeAssets.map(([key, , card]) => [key, card]));
const placeBlock = `// <generated:place-images>
// Generated by scripts/embed-assets.mjs from assets/place-*.png.
const PLACE_MAP_PNG = Object.freeze({
${mapRows.join('\n')}
});
const PLACE_CARD_PNG = Object.freeze({
${cardRows.join('\n')}
});
const PLACE_IMAGE_HASHES = {};

function placeImageHash(kind, key) {
  const source = kind === 'card' ? PLACE_CARD_PNG : PLACE_MAP_PNG;
  const cacheKey = kind + ':' + key;
  if (!source[key]) throw new Error('Нет изображения места: ' + cacheKey);
  if (!PLACE_IMAGE_HASHES[cacheKey]) {
    PLACE_IMAGE_HASHES[cacheKey] = figma.createImage(figma.base64Decode(source[key])).hash;
  }
  return PLACE_IMAGE_HASHES[cacheKey];
}

function placeMapNode(key, name) {
  const frame = figma.createFrame();
  frame.name = name;
  frame.resize(120, 116);
  frame.fills = [];
  frame.clipsContent = false;
  const art = figma.createRectangle();
  art.name = 'Иллюстрация';
  art.resize(120, 80);
  art.x = 0;
  art.y = 18;
  art.fills = [{ type: 'IMAGE', scaleMode: 'FIT', imageHash: placeImageHash('map', key) }];
  frame.appendChild(art);
  return frame;
}

function placeCardNode(key, name) {
  const frame = figma.createFrame();
  frame.name = name;
  frame.resize(343, 229);
  frame.fills = [];
  frame.clipsContent = true;
  const art = figma.createRectangle();
  art.name = 'Иллюстрация';
  art.resize(343, 229);
  art.fills = [{ type: 'IMAGE', scaleMode: 'FILL', imageHash: placeImageHash('card', key) }];
  frame.appendChild(art);
  return frame;
}
// </generated:place-images>`;

