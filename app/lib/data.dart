enum QuizKind { choice, arrange }

class QuizStep {
  const QuizStep.choice(this.question, this.options, this.correct, this.note)
    : kind = QuizKind.choice,
      answer = const [];

  const QuizStep.arrange(this.question, this.options, this.answer, this.note)
    : kind = QuizKind.arrange,
      correct = 0;

  final QuizKind kind;
  final String question;
  final List<String> options;
  final int correct;
  final List<String> answer;
  final String note;
}

