import fs from 'node:fs';
import path from 'node:path';
import { Resvg } from '@resvg/resvg-js';
const root = path.resolve(import.meta.dirname, '..');
const source = fs.readFileSync(path.resolve(root, '../app/assets/images/nav-home.svg'), 'utf8');
const icon = source.replace('width="24" height="24"', 'x="186" y="186" width="652" height="652"');
const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024"><rect width="1024" height="1024" rx="210" fill="#ffffff"/>${icon}</svg>`;
fs.writeFileSync(path.resolve(root, 'assets/icon.png'), new Resvg(svg).render().asPng());
const foreground = `<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024">${icon}</svg>`;
fs.writeFileSync(path.resolve(root, 'assets/android-icon-foreground.png'), new Resvg(foreground).render().asPng());
console.log('Generated app icon from the project home symbol.');
